export function getFleetInventorySummary(
  records: FleetMachineRecord[] = FLEET_MACHINE_INVENTORY
): FleetInventorySummary {
  const totalAssets = records.length;
  const operationalAssets = records.filter(
    (r) => r.operatingStatus === "operational"
  ).length;
  const attentionAssets = records.filter((r) => r.needsAttention).length;
  const criticalAssets = records.filter(
    (r) => r.operatingStatus === "critical"
  ).length;

  return {
    totalAssets,
    operationalAssets,
    attentionAssets,
    criticalAssets,
    fixtureSourceTag: "LOCAL FIXTURE DATASET // FLT-INV-V2.4",
  };
}

